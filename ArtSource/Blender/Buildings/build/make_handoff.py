h("    float kl = t == 0 ? e.Footprint.y : e.Footprint.x;")
h("    float s  = Mathf.Clamp(Mathf.Sqrt(b.FootprintWM * b.FootprintLM /")
h("                                      Mathf.Max(1f, kw * kl)), 0.85f, 1.2f);")
